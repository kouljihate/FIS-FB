"""Copy an existing local FIS database into the compose stack.

The container stack starts with an empty MongoDB volume.  This helper reads the
database from the host (``host.docker.internal``) and upserts the documents into
the ``mongo`` service, so a Docker deployment opens with the projects and users
that already exist on the machine.

    docker compose run --rm --entrypoint python web docker/copy_local_data.py

Source and target can be overridden:

    SOURCE_URI=mongodb://host.docker.internal:27017/FIS \
    TARGET_URI=mongodb://mongo:27017/FIS \
    docker compose run --rm --entrypoint python web docker/copy_local_data.py

The source is only read; the target documents are replaced by ``_id``, so the
script is safe to run twice.  ``event_log`` and ``ui_registry`` are not copied (the first is rebuilt by the
audit service, the second is regenerated by the app at startup).
"""

from __future__ import annotations

import os
import sys

from pymongo import MongoClient
from pymongo.errors import PyMongoError

# event_log is rebuilt by the audit service; ui_registry is regenerated by the
# app on startup (its documents are keyed, not _id-identified, so copying them
# would collide with the target's own entries).
SKIP = {"event_log", "ui_registry"}

SOURCE_URI = os.environ.get("SOURCE_URI", "mongodb://host.docker.internal:27017/FIS")
TARGET_URI = os.environ.get("TARGET_URI", "mongodb://mongo:27017/FIS")


def main() -> int:
    print("source:", SOURCE_URI)
    print("target:", TARGET_URI)
    try:
        source_db = MongoClient(SOURCE_URI, serverSelectionTimeoutMS=8000).get_default_database()
        source_db.command("ping")
        target_db = MongoClient(TARGET_URI, serverSelectionTimeoutMS=8000).get_default_database()
        target_db.command("ping")
    except PyMongoError as exc:
        print("connection failed: %s" % exc, file=sys.stderr)
        print("Is the host database running and is host.docker.internal resolvable?",
              file=sys.stderr)
        return 1

    collections = sorted(set(source_db.list_collection_names()) - SKIP)
    if not collections:
        print("source database is empty: nothing to copy")
        return 0

    for name in collections:
        copied = 0
        for document in source_db[name].find({}):
            target_db[name].replace_one({"_id": document["_id"]}, document, upsert=True)
            copied += 1
        print("  %-16s %5d document(s)" % (name, copied))

    print("done: %d collection(s) copied" % len(collections))
    print("Users, projects and the UI registry are now in the container volume.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
